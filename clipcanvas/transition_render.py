"""Native transition compositing with reusable, lossless geometry on disk.

Masks describe effect geometry only; they never contain source video. Geometry
is generated by scanline spans, not a Python or FFmpeg expression per pixel.
Each consumer hard-links immutable PNGs into its private render workspace, so
cache eviction cannot remove files from a running decoder.
"""
from collections import OrderedDict
import hashlib
import json
import math
import os
from pathlib import Path
import shutil
import struct
import tempfile
import threading
import zlib

from . import transitions

FAST_KEYS = ('circle_wipe', 'colour_wipe', 'line_wipe', 'flow')
MAX_CACHE_BYTES = 64 * 1024 * 1024
MAX_CACHE_ENTRIES = 32
_lock = threading.Lock()
_workspace = None
_entries = OrderedDict()


def _check(cancel):
    if cancel is not None and cancel.is_set():
        from .engine import RenderCancelled
        raise RenderCancelled('Preview cancelled.')


def _f32(value):
    return struct.unpack('f', struct.pack('f', value))[0]


def _frame_us(frame, fps):
    return math.floor(frame / fps * 1000000 + .5)


def _first_frame(seconds, fps):
    target = math.floor(seconds * 1000000 + .5)
    frame = max(0, math.ceil(seconds * fps - 1e-6))
    while frame and _frame_us(frame-1, fps) >= target:
        frame -= 1
    while _frame_us(frame, fps) < target:
        frame += 1
    return frame


def progress_values(overlap, offset, fps):
    """Match xfade's AVTB timestamps and single-precision progress calculation."""
    first = _first_frame(offset, fps)
    end = _first_frame(offset + overlap, fps)
    start_us = math.floor(offset * 1000000 + .5)
    duration_us = math.floor(overlap * 1000000 + .5)
    values = tuple(max(0., min(1., _f32(1 - _f32(_f32(_frame_us(i, fps)-start_us) / _f32(duration_us)))))
                   for i in range(first, max(first+1, end)))
    return first, values


def _png(path, width, height, rows):
    def chunk(kind, data):
        return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind+data) & 0xffffffff)
    compressor = zlib.compressobj(1)
    packed = bytearray()
    for row in rows:
        packed.extend(compressor.compress(b'\0'+row))
    packed.extend(compressor.flush())
    path.write_bytes(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', width, height, 8, 0, 0, 0, 0))
                     + chunk(b'IDAT', bytes(packed)) + chunk(b'IEND', b''))


def _row(width, begin, end):
    begin, end = max(0, min(width, begin)), max(0, min(width, end))
    return b'\0'*begin + b'\xff'*max(0, end-begin) + b'\0'*(width-max(begin,end))


def _rows(key, direction, width, height, p, colour=False):
    if key == 'circle_wipe':
        radius = math.hypot(width/2, height/2)*(1-p)
        for y in range(height):
            square = radius*radius - (y-height/2)**2
            if p >= 1 or square < 0:
                yield b'\xff'*width
            else:
                reach = math.sqrt(square)
                begin, end = math.ceil(width/2-reach), math.floor(width/2+reach)+1
                incoming = _row(width, begin, end)
                yield incoming.translate(_INVERSE)
        return
    extent = width if direction in ('left','right') else height
    # Only one dimension changes for a wipe. At most width+height tests,
    # followed by C byte repetitions for the complete lossless mask.
    values = bytearray()
    for coordinate in range(extent):
        axis = (extent-1-coordinate)/extent if direction in ('left','up') else coordinate/extent
        if key == 'colour_wipe':
            incoming = axis < 1-2*p
            coloured = not incoming and axis < 2-2*p
        else:
            incoming = p <= 0 or (p < 1 and axis < 1-p-.02)
            coloured = 0 < p < 1 and not incoming and axis < 1-p+.02
        values.append(255 if (coloured if colour else not incoming) else 0)
    if extent == width and direction in ('left','right'):
        row = bytes(values)
        yield from (row for _ in range(height))
    else:
        yield from (bytes([value])*width for value in values)


_INVERSE = bytes(255-value for value in range(256))


def masks(key, direction, width, height, values, scratch, tag, cancel=None):
    """Return leased image sequences; generation and resident memory stay bounded."""
    global _workspace
    payload = (key, direction if key != 'flow' else '', width, height, values)
    cache_key = hashlib.sha256(json.dumps(payload).encode()).hexdigest()
    while not _lock.acquire(timeout=.05):
        _check(cancel)
    try:
        _check(cancel)
        if _workspace is None:
            _workspace = tempfile.TemporaryDirectory(prefix='clipcanvas-transition-cache-')
        if cache_key not in _entries:
            directory = Path(_workspace.name)/cache_key
            directory.mkdir()
            try:
                phases = ('main','colour') if key in ('colour_wipe','line_wipe') else ('main',)
                for phase in phases:
                    destination = directory/phase;destination.mkdir()
                    # Final zero mask lets the incoming source pass unchanged.
                    for frame, p in enumerate((*values,0.)):
                        _check(cancel)
                        _png(destination/f'{frame:06d}.png',width,height,
                             _rows(key,direction,width,height,p,phase=='colour'))
                _entries[cache_key] = (directory, sum(p.stat().st_size for p in directory.rglob('*.png')))
            except BaseException:
                shutil.rmtree(directory,ignore_errors=True)
                raise
        directory, _ = _entries.pop(cache_key)
        _entries[cache_key] = (directory, sum(p.stat().st_size for p in directory.rglob('*.png')))
        sequences = []
        for phase in sorted(directory.iterdir()):
            destination = Path(scratch)/f'transition-{tag}-{phase.name}'
            destination.mkdir(exist_ok=True)
            for source in phase.iterdir():
                _check(cancel)
                target = destination/source.name
                if not target.exists():
                    try:os.link(source,target)
                    except OSError:shutil.copyfile(source,target)
            sequences.append((phase.name,destination/'%06d.png'))
        while len(_entries)>MAX_CACHE_ENTRIES or sum(size for _,size in _entries.values())>MAX_CACHE_BYTES:
            _, (old, _) = _entries.popitem(last=False)
            shutil.rmtree(old,ignore_errors=True)
        return dict(sequences)
    finally:
        _lock.release()


def append(args, filters, left, right, clip, overlap, offset, width, height,
           fps, right_duration, scratch, tag, cancel=None, with_alpha=False, left_frames=None):
    """Append one join, retaining a compiled xfade for existing native effects."""
    from .engine import _fmt
    key = clip.get('transition','fade')
    # Reuse all validation, including settings that happen to be inactive.
    reference = transitions.join_filter(clip,overlap,offset)
    output = f'joinv{tag}'
    if key not in FAST_KEYS:
        filters.append(f'[{left}][{right}]{reference},fps={_fmt(fps)},settb=AVTB[{output}]')
        return output
    if scratch is None:
        from .engine import RenderError
        raise RenderError('Transition composition needs a temporary working folder.')
    first, values = progress_values(overlap,offset,fps)
    if left_frames is not None:
        values = values[:max(1,left_frames-first)]
    count = len(values)
    direction = clip.get('transition_direction','left')
    # Planar alpha avoids an extra RGB round trip at overlays. Background
    # scenes stay opaque; custom xfade expressions used chroma for plane 3.
    pixel_format = 'yuva444p' if with_alpha else 'yuv444p'
    sequences = {} if key == 'flow' else masks(key,direction,width,height,values,scratch,tag,cancel)
    labels = {}
    for phase,path in sequences.items():
        index = args.count('-i')
        args.extend(['-threads','1','-framerate',_fmt(fps),'-i',str(path)])
        label = f't{tag}{phase}'
        planes = 4 if with_alpha else 3
        inputs = ''.join(f'[{label}{i}]' for i in range(planes))
        mapping = ':'.join(f'map{i}s={i}:map{i}p=0' for i in range(planes))
        filters.append(f'[{index}:v]fps={_fmt(fps)},format=gray,split={planes}{inputs}')
        filters.append(f'{inputs}mergeplanes={mapping}:format={pixel_format},'
                       f'tpad=stop_mode=clone:stop_duration={_fmt(right_duration)},settb=expr=1/{_fmt(fps)},setpts=N[{label}]')
        labels[phase] = label
    tail = f't{tag}tail'
    prefix = f't{tag}prefix'
    if first:
        # Route rather than split: the tail branch never queues the preceding
        # seconds/minutes of full-resolution pictures. Only the overlap waits.
        filters.append(f'[{left}]format={pixel_format},select=outputs=2:expr=\'if(lt(n,{first}),1,2)\'[{prefix}][{tail}raw]')
        filters.append(f'[{tail}raw]setpts=PTS-STARTPTS[{tail}]')
    else:
        filters.append(f'[{left}]format={pixel_format},setpts=PTS-STARTPTS[{tail}]')
    incoming = f't{tag}incoming'
    filters.append(f'[{right}]format={pixel_format},setpts=PTS-STARTPTS[{incoming}]')
    if key == 'flow':
        horizontal = direction in ('left','right')
        extent = width if horizontal else height
        margin = math.ceil(extent*.2)+1
        sign = 1 if direction in ('left','up') else -1
        for source, target, outgoing in ((tail,f't{tag}movea',True),(incoming,f't{tag}moveb',False)):
            positions = []
            for p in values:
                eased = (1-p)*(1-p)*(1+2*p)
                shift = sign*extent*.2*eased if outgoing else -sign*extent*.2*(1-eased)
                positions.append(margin+math.floor(shift))
            positions.append(margin)
            crop = f'crop@t{tag}{"a" if outgoing else "b"}'
            coordinate = 'x' if horizontal else 'y'
            commands = ';'.join(f'{_fmt(max(0,i/fps-.000002))} {crop} {coordinate} {position}' for i,position in enumerate(positions))
            padding = f'{width+2*margin}:{height}:{margin}:0' if horizontal else f'{width}:{height+2*margin}:0:{margin}'
            borders = f'left={margin}:right={margin}' if horizontal else f'top={margin}:bottom={margin}'
            x,y = (margin,0) if horizontal else (0,margin)
            filters.append(f'[{source}]pad={padding},fillborders={borders}:mode=smear,sendcmd=c=\'{commands}\','
                           f'{crop}={width}:{height}:{x}:{y}:exact=1[{target}]')
        tail, incoming = f't{tag}movea',f't{tag}moveb'
    result = f't{tag}merged'
    if key == 'flow':
        phase = (_frame_us(first,fps)-math.floor(offset*1000000+.5))/1000000
        filters.append(f'[{tail}][{incoming}]xfade=transition=fade:duration={_fmt(overlap)}:offset={_fmt(-phase)}[{result}]')
    else:
        filters.append(f'[{tail}]tpad=stop_mode=clone:stop_duration={_fmt(right_duration)}[{tail}pad]')
        # Multiple framesync inputs must share integer frame timestamps.
        # Near-equal microseconds at fractional rates otherwise create extra
        # events, advancing the second wipe's enable counter prematurely.
        filters.append(f'[{tail}pad]settb=expr=1/{_fmt(fps)},setpts=N[{tail}grid]')
        filters.append(f'[{incoming}]settb=expr=1/{_fmt(fps)},setpts=N[{incoming}grid]')
        filters.append(f'[{incoming}grid][{tail}grid][{labels["main"]}]maskedmerge=enable=\'lt(n,{count})\'[{result}]')
    if 'colour' in labels:
        colour = clip.get('transition_colour',transitions.DEFAULT_COLOUR)
        red,green,blue = (int(colour[i:i+2],16) for i in (1,3,5))
        y = round(16+.256788*red+.504129*green+.097906*blue)
        u = round(128-.148223*red-.290993*green+.439216*blue)
        v = round(128+.439216*red-.367788*green-.071427*blue)
        filters.append(f'color=c=0x{colour[1:]}:s={width}x{height}:r={_fmt(fps)}:d={_fmt(right_duration+1/fps)},'
                       f'fps={_fmt(fps)},format={pixel_format},lut=y={y}:u={u}:v={v}'+(f':a=255' if with_alpha else '')+f',settb=expr=1/{_fmt(fps)},setpts=N[t{tag}paint]')
        filters.append(f'[{result}][t{tag}paint][{labels["colour"]}]maskedmerge=enable=\'lt(n,{count})\'[t{tag}coloured]')
        result = f't{tag}coloured'
    if first:
        filters.append(f'[{prefix}][{result}]concat=n=2:v=1:a=0,fps={_fmt(fps)},settb=AVTB[{output}]')
    else:
        filters.append(f'[{result}]fps={_fmt(fps)},settb=AVTB[{output}]')
    return output
